import { describe, expect, it } from "vitest";
import { plural } from "./format";

describe("согласование числительных", () => {
  it.each([
    [1, "строка"],
    [2, "строки"],
    [4, "строки"],
    [5, "строк"],
    [11, "строк"],
    [14, "строк"],
    [21, "строка"],
    [22, "строки"],
    [101, "строка"],
    [111, "строк"],
    [1002, "строки"],
    [0, "строк"],
  ])("%i → %s", (count, expected) => {
    //#«9 Предупреждение» и «21 строк» по-русски одинаково неверны, а подпись под числом
    //#читают чаще, чем само число
    expect(plural(count, "строка", "строки", "строк")).toBe(expected);
  });
});
