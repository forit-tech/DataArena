"""Что шаг конвейера делает с колонками — с точки зрения их происхождения.

Это отдельный контракт операции, и он намеренно не выводится из `reads`. `reads` отвечает
на вопрос «на какие колонки шаг опирается» и нужен для проверки перестановки шагов.
Происхождению нужен другой вопрос: «значения какой колонки стали другими». Сортировка
читает колонку, но ни одного её значения не меняет; из `reads` этого не узнать, и раздел
происхождения показывал сортировку как преобразование колонки.

Эффекты — разные типы, а не один словарь с полем «вид». Шаг, который меняет только строки,
возвращает `DatasetOnlyEffect`, и у этого типа просто нет поля, куда можно было бы вписать
колонку: сортировка не может случайно оказаться в истории колонки.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class ColumnMutation:
    """Значения колонок изменены на месте: имя и происхождение прежние, добавляется событие."""

    columns: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class ColumnRename:
    """Колонка сменила имя. Происхождение и прошлое переезжают вместе с ней."""

    source: str
    target: str


@dataclass(frozen=True, slots=True)
class ColumnCreate:
    """Появилась новая колонка, вычисленная из входных.

    Входов — кортеж, а не одно имя: копирование читает одну колонку, но вычисляемая
    колонка вроде «цена × количество» читает несколько, и модель не должна ломаться, когда
    такая операция появится.
    """

    inputs: tuple[str, ...]
    output: str


@dataclass(frozen=True, slots=True)
class ColumnDrop:
    """Колонки удалены. Их история уходит вместе с ними и не достаётся будущим тёзкам."""

    columns: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class DatasetOnlyEffect:
    """Шаг меняет набор или порядок строк либо порядок колонок, но не значения.

    Отбор, удаление строк, сортировка, дедупликация и перестановка колонок относятся сюда.
    Они меняют датасет, но ни у одной колонки не появляется значения, которого в ней
    не было, — поэтому в истории колонки их нет.
    """


ColumnEffect = ColumnMutation | ColumnRename | ColumnCreate | ColumnDrop | DatasetOnlyEffect
