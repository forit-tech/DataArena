"""Пороги проверок Health — все в одном месте, с именами и объяснениями.

Пороги не вынесены в настройки сознательно. Настройка, которую никто не трогает, —
это спрятанное решение: она выглядит как гибкость, а на деле означает, что порог
не выбран, а перепоручен. Здесь он выбран, назван и объяснён, и менять его —
осознанная правка кода, а не молчаливое изменение поведения.

Разбросать эти числа по проверкам нельзя по той же причине, по которой их не стоит
делать настройками: тогда «почему 0,99» перестанет иметь ответ.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Thresholds:
    """Границы срабатывания проверок."""

    #ниже этого числа строк почти любая проверка вырождается: на трёх строках «колонка
    #постоянна» и «значения уникальны» верны одновременно и не значат ничего
    min_rows_for_column_checks: int = 20

    #доля доминирующего значения, при которой колонка считается почти постоянной.
    #0,99 — а не 0,95: при 95% в колонке ещё остаётся заметное меньшинство, и объявлять
    #её вырожденной рано
    near_constant_share: float = 0.99

    #доля уникальных значений, выше которой колонка отмечается как высококардинальная.
    #Это сигнал, а не дефект: у адреса или комментария так и должно быть
    high_cardinality_share: float = 0.5
    #и при этом уникальных должно быть достаточно много: 6 из 10 — не высокая
    #кардинальность, а маленький датасет
    high_cardinality_min_unique: int = 100

    #колонка считается похожей на идентификатор, если значения уникальны и не пусты.
    #Порог доли нужен, потому что единственный повтор не должен отменять наблюдение
    identifier_min_unique_share: float = 0.999

    #множитель межквартильного размаха для выбросов. 1,5 — общепринятая граница
    #«умеренного выброса»; она названа здесь, чтобы не выглядеть как магия в коде
    outlier_iqr_multiplier: float = 1.5

    #доля значений другого типа, ниже которой смесь типов считается опечаткой,
    #а не двумя разными смыслами в одной колонке
    mixed_types_max_minority_share: float = 0.2

    #сколько строк просматривается при отборе кандидатов на смесь типов.
    #Отбор по выборке допустим, подсчёт — нет: см. правило точности
    type_probe_sample_rows: int = 10_000

    #сколько примеров значений кладётся в находку. Больше не нужно человеку
    #и не нужно интерфейсу, а ответ раздувается
    max_evidence_values: int = 10
    #и каждое обрезается: в данных встречаются строки на мегабайт
    max_evidence_value_length: int = 200

    #предел длины одного значения в предикате. Измерено: строка на два мегабайта
    #в доминирующем значении раздувала сохранённый отчёт до 2 МБ на датасете из 300 строк —
    #ответ API при этом оставался маленьким, поэтому заметить это можно было только поздно.
    #Предикат с таким значением не нужен никому: показать «строки, где значение равно
    #двухмегабайтной строке» можно и без её хранения — но честнее не показывать вовсе
    max_filter_value_length: int = 4_000

    #сколько значений допускается положить в предикат провала в строки.
    #Выше этого предиката не существует — находка остаётся без провала,
    #а не отдаёт список на миллион элементов
    max_filter_values: int = 200

    #предел числа колонок, обрабатываемых одним планом. Тысяча колонок на несколько
    #показателей — это тысячи выражений в одном запросе, и план надо дробить
    columns_per_batch: int = 100

    #выше этой кардинальности разнописание регистра не ищется. Не из осторожности,
    #а по измерению: группировка колонки с пятью миллионами различных значений стоит
    #около гигабайта памяти — и это не зависит от способа запроса, проверено тремя
    #вариантами (только счётчики — 1083 МБ, только окно — 991 МБ, со списками — 1274 МБ).
    #При этом смысла в такой проверке нет: колонка с миллионами различных значений —
    #это адрес или комментарий, а не категория, и «Москва» против «москва» среди них
    #не то, ради чего проверка заводилась
    max_case_variant_unique: int = 50_000


THRESHOLDS = Thresholds()
